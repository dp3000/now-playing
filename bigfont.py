GLYPHS = {ch: rows + ["." * len(rows[0])] * (8 - len(rows)) for ch, rows in _G.items()}

# Typographic punctuation lyrics often use, mapped to what the font has.
_SUBST = str.maketrans({"‘": "'", "’": "'", "‚": ",", "“": '"', "”": '"', "„": '"', "–": "-", "—": "-",
                        "…": "...", "´": "'", "`": "'", "«": '"', "»": '"', " ": " "})
_BLOCKS = [" ", "▄", "▀", "█"]  # index = top*2 + bottom


def to_font_text(text):
    """Map text onto the font's characters (strip accents, straighten quotes); '?' for the rest."""
    text = " ".join(text.translate(_SUBST).split())
    text = "".join(c for c in unicodedata.normalize("NFKD", text) if not unicodedata.combining(c))
    return "".join(c if c in GLYPHS else "?" for c in text)


def coverage(text):
    """Fraction of a line's visible characters the font can draw (low for e.g. Japanese lyrics)."""
    chars = [c for c in text if not c.isspace()]
    if not chars:
        return 1.0
    ok = sum(1 for c in to_font_text("".join(chars)) if c != "?")
    return ok / len(chars)


_BOLD = {}
# Letters whose 1-pixel gaps would fill in when thickened get wider shapes in bold.
_WIDE = {
    "M": ["#.......#", "##.....##", "#.#...#.#", "#..#.#..#", "#...#...#", "#.......#", "#.......#"],
    "W": ["#.......#", "#.......#", "#.......#", "#...#...#", "#..#.#..#", "#.#...#.#", "##.....##"],
    "m": [".........", ".........", "####.###.", "#...#...#", "#...#...#", "#...#...#", "#...#...#"],
    "w": [".........", ".........", "#...#...#", "#...#...#", "#...#...#", "#...#...#", ".###.###."],
}
_WIDE = {ch: rows + ["." * len(rows[0])] * (8 - len(rows)) for ch, rows in _WIDE.items()}


def glyph(ch, bold=False):
    """Glyph rows; bold thickens every stroke to 2 pixels (glyph gets 1 pixel wider)."""
    if not bold or ch == " ":
        return GLYPHS[ch]
    if ch not in _BOLD:
        _BOLD[ch] = ["".join("#" if "#" in (row + ".")[max(x - 1, 0):x + 1] else "." for x in range(len(row) + 1))
                     for row in _WIDE.get(ch, GLYPHS[ch])]
    return _BOLD[ch]


def _word_px(word, bold=False):
    return sum(len(glyph(c, bold)[0]) + 1 for c in word) - 1 if word else 0


def render(text, scale, width, bold=False):
    """Big-text rows for `text`, wrapped to `width` columns.

    -> (rows, n): rows is a list of (row_width, [(dx, ch, k)]) where k is the index of the
    source character the cell belongs to (for karaoke); n is the number of source characters.
    Blank pixels inside the text are included as " " cells. Wrapped big rows are separated by
    an empty spacer row (0, []).
    """
    text = to_font_text(text) or "♪"
    words = text.split(" ")
    max_px = max(width // scale, 1)
    space_px = len(GLYPHS[" "][0]) + 2  # space glyph plus the gaps on either side

    lines, line, line_px = [], [], 0
    for word in words:
        px = _word_px(word, bold)
        if line and line_px + space_px + px > max_px:
            lines.append(line)
            line, line_px = [word], px
        else:
            line_px += (space_px if line else 0) + px
            line.append(word)
    lines.append(line)

    rows, k = [], 0
    for li, words_in_row in enumerate(lines):
        bitmap, kmap = [""] * 8, []
        for wi, word in enumerate(words_in_row):
            if wi:  # the space between words belongs to that space character
                for r in range(8):
                    bitmap[r] += "." + GLYPHS[" "][r] + "."
                kmap += [k] * space_px
                k += 1
            for ci, ch in enumerate(word):
                g = glyph(ch, bold)
                gap = "." if ci < len(word) - 1 else ""
                for r in range(8):
                    bitmap[r] += g[r] + gap
                kmap += [k] * (len(g[0]) + len(gap))
                k += 1
        k += 1  # the space consumed by wrapping
        if li:
            rows.append((0, []))
        # scale up, then fold pairs of pixel rows into half-block cells
        px_rows = [row.replace(".", " ").replace("#", "█") for row in bitmap]
        px_rows = ["".join(c * scale for c in row) for row in px_rows for _ in range(scale)]
        kmap = [kk for kk in kmap for _ in range(scale)]
        for cr in range(len(px_rows) // 2):
            top, bottom = px_rows[2 * cr], px_rows[2 * cr + 1]
            cells = [(x, _BLOCKS[(top[x] != " ") * 2 + (bottom[x] != " ")], kmap[x]) for x in range(len(top))]
            rows.append((len(top), cells))
    return rows, len(text)


def height(text, scale, width, bold=False):
    rows, _ = render(text, scale, width, bold)
    return len(rows)


def fits(text, scale, width, bold=False):
    """Whether every word fits on a row at this scale."""
    return all(_word_px(w, bold) * scale <= width for w in to_font_text(text).split(" "))
